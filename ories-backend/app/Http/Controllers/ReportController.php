<?php

namespace App\Http\Controllers;

use App\Models\ProjectOutcome;
use App\Models\User;
use App\Services\ReportService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Validation\Rule;
use Symfony\Component\HttpFoundation\StreamedResponse;

class ReportController extends Controller
{
    public function __construct(private ReportService $reports) {}

    public function types(): JsonResponse
    {
        return response()->json([
            'types' => collect(ReportService::TYPES)->map(fn ($label, $key) => ['key' => $key, 'label' => $label])->values(),
            'ranges' => ReportService::RANGES,
        ]);
    }

    public function show(Request $request, string $type): JsonResponse|StreamedResponse
    {
        abort_unless(array_key_exists($type, ReportService::TYPES), 404);

        $filters = $request->validate([
            'range' => ['nullable', Rule::in(ReportService::RANGES)],
            'from' => 'nullable|required_if:range,custom|date',
            'to' => 'nullable|required_if:range,custom|date|after_or_equal:from',
            'group_by' => 'nullable|in:year,quarter,month',
            'office' => ['nullable', Rule::in(User::OFFICES)],
            'campus_id' => 'nullable|integer',
            'unit_id' => 'nullable|integer',
            'stage' => 'nullable|string',
            'outcome' => ['nullable', Rule::in(ProjectOutcome::TYPES)],
            'indexing' => ['nullable', Rule::in(ProjectOutcome::INDEXING)],
            'user_id' => 'nullable|integer',
            'year' => 'nullable|integer|min:1990|max:2100',
            'format' => 'nullable|in:json,csv',
        ]);

        $report = $this->reports->generate($request->user(), $type, $filters);

        if (($filters['format'] ?? 'json') === 'csv') {
            return $this->csv($report);
        }

        return response()->json($report);
    }

    private function csv(array $report): StreamedResponse
    {
        $filename = 'ories-'.$report['meta']['type'].'-'.now()->format('Ymd-His').'.csv';

        return response()->streamDownload(function () use ($report) {
            $out = fopen('php://output', 'w');
            fwrite($out, "\xEF\xBB\xBF"); // UTF-8 BOM so Excel reads accents correctly
            $put = fn (array $cells) => fputcsv($out, array_map(self::cell(...), $cells));
            $put([$report['title']]);
            $put(['Period', $report['meta']['from'].' to '.$report['meta']['to'], 'Scope', $report['meta']['scope']]);
            $put([]);

            $keys = array_column($report['columns'], 'key');
            $put(array_column($report['columns'], 'label'));
            foreach ($report['rows'] as $row) {
                $put(array_map(fn ($k) => $row[$k] ?? '', $keys));
            }
            if ($report['totals']) {
                $put(array_map(fn ($k) => $report['totals'][$k] ?? '', $keys));
            }

            $put([]);
            $put(['Generated by', $report['meta']['generated_by'], 'on', $report['meta']['generated_at']]);
            fclose($out);
        }, $filename, ['Content-Type' => 'text/csv; charset=UTF-8']);
    }

    /**
     * Text that starts like a formula is prefixed with an apostrophe so spreadsheet apps show it as text.
     */
    private static function cell(mixed $value): mixed
    {
        return is_string($value) && preg_match('/^[=+\-@\t\r]/', $value) ? "'".$value : $value;
    }
}
